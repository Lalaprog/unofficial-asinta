import { randomUUID } from 'node:crypto';
import { NextRequest, NextResponse } from 'next/server';
import { createServerSupabaseClient } from '@/lib/supabase/server';
import { createServiceRoleClient, isServiceRoleConfigured } from '@/lib/supabase/admin';
import { requireSessionAssurance } from '@/lib/auth/session-assurance';
import { requireFounder } from '@/lib/auth/serverRole';
import { checkProjectPhoto, photoMatchesType, PROJECT_PHOTO_BUCKET, PROJECT_PHOTO_MAX_BYTES } from '@/lib/projects/photos';

export const runtime = 'nodejs';
export const dynamic = 'force-dynamic';
const noStore = { 'Cache-Control': 'private, no-store', 'X-Content-Type-Options': 'nosniff' };
const uuid = /^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$/i;
const fail = (message: string, status: number) => NextResponse.json({ error: message }, { status, headers: noStore });
type Context = { params: { id: string } };

/** Never call the service-role client before authenticating and checking scope. */
async function authorize(id: string, write: boolean) {
  if (!uuid.test(id)) return { error: fail('Project not found.', 404) };
  const session = createServerSupabaseClient();
  if (write) {
    const founder = await requireFounder(session);
    if (!founder.ok) return { error: fail(founder.error || 'Not authorized.', founder.status) };
  } else {
    const { data, error } = await session.auth.getUser();
    if (error || !data.user) return { error: fail('Authentication required.', 401) };
    const assurance = await requireSessionAssurance(session);
    if (!assurance.ok) return { error: fail(assurance.error, assurance.status) };
  }
  // visible_projects is the existing audited function which checks Founder or
  // assigned Supervisor, using the caller's JWT, not the service role.
  const { data: project, error } = await session.rpc('visible_projects').eq('id', id).maybeSingle();
  if (error) return { error: fail('Unable to verify project access.', 503) };
  if (!project) return { error: fail('Project not found.', 404) };
  if (!isServiceRoleConfigured()) return { error: fail('Photo service unavailable.', 503) };
  return { admin: createServiceRoleClient() };
}

export async function GET(req: NextRequest, { params }: Context) {
  try {
    const { admin, error } = await authorize(params.id, false);
    if (error || !admin) return error!;
    const { data: row, error: dbError } = await admin.from('project_photos').select('object_path,version').eq('project_id', params.id).maybeSingle();
    if (dbError) return fail('Could not load project photo.', 503);
    if (req.nextUrl.searchParams.get('info') === '1') return NextResponse.json({ hasPhoto: Boolean(row), version: row?.version ?? null }, { headers: noStore });
    if (!row) return fail('No project photo.', 404);
    const { data: blob, error: storageError } = await admin.storage.from(PROJECT_PHOTO_BUCKET).download(row.object_path);
    if (storageError || !blob) return fail('Could not load project photo.', 503);
    // Object paths are generated by the server; MIME is set only from the
    // validated allowlist at upload, and never from a user-supplied filename.
    const mime = blob.type.toLowerCase();
    if (!['image/jpeg', 'image/png', 'image/webp'].includes(mime)) return fail('Could not load project photo.', 503);
    return new Response(await blob.arrayBuffer(), { headers: { ...noStore, 'Content-Type': mime, 'Content-Disposition': 'inline' } });
  } catch { return fail('Could not load project photo.', 503); }
}

export async function PUT(req: NextRequest, { params }: Context) {
  try {
    const { admin, error } = await authorize(params.id, true);
    if (error || !admin) return error!;
    // A multipart request includes modest overhead beyond the file itself.
    const contentLength = Number(req.headers.get('content-length'));
    if (Number.isFinite(contentLength) && contentLength > PROJECT_PHOTO_MAX_BYTES + 65536) return fail('Choose a photo no larger than 3 MB.', 413);
    const form = await req.formData();
    const candidate = form.get('photo');
    const expected = form.get('version');
    if (typeof expected !== 'string' || (expected !== '' && !uuid.test(expected))) return fail('Refresh the project before trying again.', 400);
    const file = candidate && typeof candidate !== 'string' ? candidate : null;
    const fileError = checkProjectPhoto(file);
    if (fileError || !file) return fail(fileError || 'Choose a photo.', 422);
    const mime = file.type.toLowerCase();
    const bytes = new Uint8Array(await file.arrayBuffer());
    if (!photoMatchesType(bytes, mime)) return fail('That file is not a valid JPEG, PNG or WebP photo.', 422);
    const { data: previous, error: readError } = await admin.from('project_photos').select('object_path,version').eq('project_id', params.id).maybeSingle();
    if (readError) return fail('Could not check the current photo.', 503);
    if ((previous?.version ?? '') !== expected) return fail('The photo changed elsewhere. Refresh before trying again.', 409);
    const version = randomUUID();
    const extension = mime === 'image/jpeg' ? 'jpg' : mime === 'image/png' ? 'png' : 'webp';
    const path = `${params.id}/${version}.${extension}`;
    const { error: uploadError } = await admin.storage.from(PROJECT_PHOTO_BUCKET).upload(path, bytes, { contentType: mime, upsert: false });
    if (uploadError) return fail('Could not upload the photo. Please try again.', 503);
    const values = { object_path: path, version, updated_at: new Date().toISOString() };
    if (previous) {
      const { data, error: updateError } = await admin.from('project_photos').update(values).eq('project_id', params.id).eq('version', expected).select('version').maybeSingle();
      // An error may be an ambiguous success; leave the new object intact.
      if (updateError) return fail('Save was not confirmed. Refresh the project before trying again.', 503);
      if (!data) { await admin.storage.from(PROJECT_PHOTO_BUCKET).remove([path]); return fail('The photo changed elsewhere. Refresh before trying again.', 409); }
    } else {
      const { error: insertError } = await admin.from('project_photos').insert({ project_id: params.id, ...values });
      // An ambiguous insert must not delete a possibly referenced object.
      if (insertError) return fail('Save was not confirmed. Refresh the project before trying again.', 409);
    }
    // Cleanup is best-effort and only after the new reference is confirmed.
    if (previous) await admin.storage.from(PROJECT_PHOTO_BUCKET).remove([previous.object_path]);
    return NextResponse.json({ hasPhoto: true, version }, { headers: noStore });
  } catch { return fail('Save was not confirmed. Refresh the project before trying again.', 503); }
}

export async function DELETE(req: NextRequest, { params }: Context) {
  try {
    const { admin, error } = await authorize(params.id, true);
    if (error || !admin) return error!;
    const payload = await req.json().catch(() => null);
    if (typeof payload?.version !== 'string' || !uuid.test(payload.version)) return fail('Refresh the project before trying again.', 400);
    const { data, error: deleteError } = await admin.from('project_photos').delete().eq('project_id', params.id).eq('version', payload.version).select('object_path').maybeSingle();
    if (deleteError) return fail('Removal was not confirmed. Refresh the project before trying again.', 503);
    if (!data) return fail('The photo changed elsewhere. Refresh before trying again.', 409);
    // Best effort only: a failed object deletion does not restore the reference.
    await admin.storage.from(PROJECT_PHOTO_BUCKET).remove([data.object_path]);
    return NextResponse.json({ hasPhoto: false, version: null }, { headers: noStore });
  } catch { return fail('Removal was not confirmed. Refresh the project before trying again.', 503); }
}
